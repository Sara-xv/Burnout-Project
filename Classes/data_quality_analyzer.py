    def _fig_to_base64(self, fig) -> str:
        import io
        import base64
        buf = io.BytesIO()
        fig.savefig(buf, format="png", dpi=150, bbox_inches="tight",
                    facecolor=self.CHART_BG, edgecolor="none")
        plt.close(fig)
        buf.seek(0)
        return base64.b64encode(buf.read()).decode("ascii")

    def _style_axes(self, ax):
        ax.set_facecolor(self.CHART_BG)
        for spine_name in ("top", "right"):
            ax.spines[spine_name].set_visible(False)
        for spine_name in ("left", "bottom"):
            ax.spines[spine_name].set_color(self.CHART_GRID)
        ax.tick_params(colors=self.CHART_TEXT, labelsize=9)
        ax.grid(axis="y", color=self.CHART_GRID, linewidth=0.9, alpha=0.35)
        ax.set_axisbelow(True)

    def _build_outlier_chart(self, col: str, series: pd.Series, info: dict) -> Optional[str]:
        if not MATPLOTLIB_AVAILABLE:
            return None
        clean = series.dropna()
        if clean.empty:
            return None

        fig, ax = plt.subplots(figsize=(6.6, 3.1))
        n_bins = min(40, max(10, int(len(clean) ** 0.5)))
        ax.hist(clean, bins=n_bins, color=self.CHART_ACCENT, alpha=0.85, zorder=3, edgecolor=self.CHART_BG)

        if "lower_bound" in info.get("iqr", {}):
            lb = info["iqr"]["lower_bound"]
            ub = info["iqr"]["upper_bound"]
            ax.axvline(lb, color=self.CHART_RED, linestyle="--", linewidth=1.4, zorder=4, label="IQR bound")
            ax.axvline(ub, color=self.CHART_RED, linestyle="--", linewidth=1.4, zorder=4)
            ax.legend(fontsize=8, frameon=False, labelcolor=self.CHART_TEXT)

        self._style_axes(ax)
        ax.set_title(f"Distribution — {col}", fontsize=11, color="#212121", fontweight="bold", pad=10)
        ax.set_ylabel("Count", fontsize=9, color=self.CHART_TEXT)
        fig.tight_layout()
        return self._fig_to_base64(fig)

